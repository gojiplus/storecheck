"""Review a support-routing data release from proposal through validation.

The customer hypothesis is an application engineer reviewing examples supplied
by support operations. All data and costs are synthetic. Hashing and nearest-label
classification are a deterministic stand-in for the customer's application.

Run: uv run python examples/release_review.py --output-dir /tmp/storecheck-review
"""

from __future__ import annotations

import argparse
from datetime import UTC, datetime
from pathlib import Path

from storecheck import (
    Case,
    ComparisonReport,
    EmbeddingRetriever,
    EvalSet,
    HashingEmbedder,
    LabelDef,
    MajorityVoteDecider,
    Objective,
    Pipeline,
    Prediction,
    Query,
    Row,
    Snapshot,
    Store,
    Taxonomy,
    compare_stores,
    run_checks,
)
from storecheck.checks import SchemaCheck, TaxonomyValidityCheck


def make_cases(records: list[tuple[str, str, str]], role: str) -> EvalSet:
    """Create synthetic cases with explicit data roles and independent customers.

    Args:
        records: Case identifiers, query texts, and expected labels.
        role: Discovery or validation role.

    Returns:
        Cases with illustrative business costs and named slices.
    """
    cases = []
    for identifier, text, label in records:
        slices = {"permissions"} if label == "authorization" else set()
        if "sso" in identifier:
            slices.add("sso")
        cases.append(
            Case(
                identifier,
                text,
                label,
                slices=frozenset(slices),
                cost={"authentication": 1, "authorization": 50, "billing": 5}[label],
                metadata={"customer": f"{role}-{identifier}"},
            )
        )
    return EvalSet(cases, name=role)


def evaluate(
    baseline: Store,
    candidate: Store,
    cases: EvalSet,
    taxonomy: Taxonomy,
    discovery: EvalSet | None = None,
) -> ComparisonReport:
    """Run one fixed application against both snapshots under the review policy.

    Args:
        baseline: Currently deployed source examples.
        candidate: Proposed source examples.
        cases: Cases for this review stage.
        taxonomy: Allowed routing categories.
        discovery: Cases used to choose the edit, supplied only for validation.

    Returns:
        A comparison artifact retaining predictions, evidence, and gate findings.
    """
    embedder = HashingEmbedder()
    retriever = EmbeddingRetriever(embedder, k=1)
    decider = MajorityVoteDecider()

    def application(query: Query, snapshot: Store | Snapshot) -> Prediction:
        if not isinstance(snapshot, Store):
            raise ValueError("the local demo requires Store snapshots")
        rows = retriever.retrieve(query.text, snapshot, scope=query.scope)
        return Prediction(decider.decide(query.text, rows), tuple(rows))

    pipeline = Pipeline(
        application,
        {
            "application": "synthetic-support-routing-v1",
            "retrieval": {"embedder": embedder.name, "k": 1},
            "decision": "nearest-example-label-v1",
        },
    )
    return compare_stores(
        baseline,
        candidate,
        cases,
        pipeline=pipeline,
        objective=Objective(
            max_right_to_wrong_cost=0,
            min_slice_metric={"permissions": 1.0, "sso": 1.0},
            min_slice_cases={"permissions": 2, "sso": 2}
            if discovery is not None
            else {},
        ),
        taxonomy=taxonomy,
        discovery=discovery,
        group_key="customer" if discovery is not None else None,
    )


def show_changes(report: ComparisonReport) -> None:
    """Print changed predictions with the evidence that produced them.

    Args:
        report: Completed discovery or validation comparison.
    """
    print(report.summary())
    for result in report.to_dict()["cases"]:
        if result["transition"] == "unchanged":
            continue
        print(f"  Query: {result['case']['text']}")
        print(f"  Expected: {result['case']['label']}")
        for side in ("baseline", "candidate"):
            prediction = result[side]
            evidence = "; ".join(
                f"{row['id']}: {row['text']!r} [{row['label']}]"
                for row in prediction["evidence"]
            )
            print(f"  {side}: {prediction['prediction']} via {evidence}")


def main(argv: list[str] | None = None) -> int:
    """Walk through a proposed edit, discovery review, and final validation.

    The revision is scripted to illustrate human review, not automatically
    generated by storecheck. Validation is evaluated only after the discovery
    gate accepts that revision. No database or deployment is modified.

    Args:
        argv: Optional command-line arguments.

    Returns:
        Final gate exit status; the deliberately rejected first proposal is expected.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path)
    args = parser.parse_args(argv)
    taxonomy = Taxonomy(
        [
            LabelDef("authentication", "Cannot prove identity or start a session."),
            LabelDef("authorization", "Signed in but lacks permission."),
            LabelDef("billing", "Invoices, charges, refunds, and payment methods."),
        ]
    )
    source = [
        ("password", "login password rejected invalid credentials", "authentication"),
        ("session", "session expired sign in again login", "authentication"),
        (
            "reports",
            "signed in but access denied opening reports folder",
            "authorization",
        ),
        ("viewer", "viewer role permission denied editing document", "authorization"),
        ("invoice", "duplicate invoice charge refund", "billing"),
        ("card", "update payment card subscription", "billing"),
    ]
    baseline = Store(
        [
            Row(
                text,
                label,
                id=identifier,
                created_at=datetime(2026, 1, 1, tzinfo=UTC),
                author="support-operations",
                taxonomy_version=taxonomy.label_version(label),
            )
            for identifier, text, label in source
        ],
        name="deployed",
    )
    proposed = baseline.add(
        Row(
            "SSO login access denied",
            "authentication",
            id="sso-example",
            created_at=datetime(2026, 2, 1, tzinfo=UTC),
            author="support-operations",
            taxonomy_version=taxonomy.label_version("authentication"),
        )
    )
    discovery = make_cases(
        [
            ("d-sso", "SSO identity provider access denied", "authentication"),
            (
                "d-permission",
                "SSO login works but access denied to reports folder",
                "authorization",
            ),
            ("d-invoice", "refund duplicate invoice", "billing"),
        ],
        "discovery",
    )
    validation = make_cases(
        [
            (
                "v-sso-1",
                "identity provider displays access denied during SSO",
                "authentication",
            ),
            (
                "v-sso-2",
                "SSO credentials rejected by identity provider",
                "authentication",
            ),
            (
                "v-permission-1",
                "SSO login succeeded reports folder says access denied",
                "authorization",
            ),
            (
                "v-permission-2",
                "viewer role cannot edit document permission denied",
                "authorization",
            ),
            ("v-password", "invalid password when login rejected", "authentication"),
            ("v-session", "session expired please sign in again", "authentication"),
            ("v-invoice", "duplicate charge on invoice need refund", "billing"),
            ("v-card", "subscription payment card update", "billing"),
        ],
        "validation",
    )
    print("Customer: the engineer responsible for support-ticket routing.")
    print("Job: review a data edit before releasing it to the application.")
    print("Synthetic cases and costs; local deterministic application; no deployment.")
    print("\n1. Support operations proposes one new SSO example.")
    structure = run_checks(
        proposed, [SchemaCheck(), TaxonomyValidityCheck()], taxonomy=taxonomy
    )
    print(f"Schema and taxonomy: {'PASS' if structure.passed() else 'FAIL'}")
    if not structure.passed():
        print(structure.summary())
        return 1
    print("\n2. Review the proposal using discovery cases.")
    initial = evaluate(baseline, proposed, discovery, taxonomy)
    show_changes(initial)

    print("\n3. The reviewer clarifies the example using the discovery findings.")
    revised = proposed.edit(
        "sso-example",
        text="SSO identity provider rejects credentials before session starts",
    )
    revision = evaluate(baseline, revised, discovery, taxonomy)
    show_changes(revision)
    if revision.exit_code:
        print("Stop: the revision failed discovery review. Validation was not opened.")
        return revision.exit_code

    print("\n4. Freeze the revision; evaluate it once on separate validation cases.")
    final = evaluate(baseline, revised, validation, taxonomy, discovery=discovery)
    show_changes(final)
    if args.output_dir is not None:
        destination = args.output_dir
        destination.mkdir(parents=True, exist_ok=True)
        for name, store in (
            ("baseline", baseline),
            ("proposed", proposed),
            ("revised", revised),
        ):
            store.to_jsonl(str(destination / f"{name}.jsonl"))
        discovery.to_jsonl(str(destination / "discovery.jsonl"))
        validation.to_jsonl(str(destination / "validation.jsonl"))
        taxonomy.to_json(str(destination / "taxonomy.json"))
        for name, report in (
            ("discovery-proposed", initial),
            ("discovery-revised", revision),
            ("validation-revised", final),
        ):
            report.to_json(destination / f"{name}.json")
        print(f"\nReview artifacts: {destination}")
    if final.exit_code == 0:
        print("\nEligible for release review on these cases. No deployment performed.")
        print(
            "Tested candidate fingerprint: "
            f"{final.to_dict()['manifest']['candidate']['fingerprint']}"
        )
    else:
        print("\nRelease blocked. Do not tune further edits on this validation set.")
    return final.exit_code


if __name__ == "__main__":
    raise SystemExit(main())
